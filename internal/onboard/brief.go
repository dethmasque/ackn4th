// BriefBytes is the default size budget for a brief, about 8k tokens.
const BriefBytes = 32 << 10

// Brief describes the workspace for an agent joining a task, in at most
// maxBytes. It is generated locally from the files.
func Brief(ws *workspace.Workspace, maxBytes int) string {
	var b strings.Builder
	b.WriteString("# Project brief\n\nGenerated by ackn4th from the workspace as you joined: a map to start from, not the whole story. Read files before relying on details.\n\n")

	ignore := loadIgnore(ws)
	entries, truncated, _ := ws.List(".", 64, maxSnapshotFiles)
	var files []workspace.Entry
	var dirs []workspace.Entry
	for _, e := range entries {
		if ignore.match(e.Path) {
			continue
		}
		if e.IsDir {
			dirs = append(dirs, e)
		} else {
			files = append(files, e)
		}
	}
	if len(files) == 0 {
		b.WriteString("The workspace is empty: you are starting from scratch.\n")
		return b.String()
	}

	// Overview: size, languages, branch.
	var total int64
	langs := map[string]int{}
	for _, f := range files {
		total += f.Size
		if l, ok := languages[strings.ToLower(path.Ext(f.Path))]; ok {
			langs[l]++
		}
	}
	more := ""
	if truncated {
		more = "+"
	}
	fmt.Fprintf(&b, "- %d%s files in %d directories, %s\n", len(files), more, len(dirs), ui.Bytes(int(total)))
	if len(langs) > 0 {
		fmt.Fprintf(&b, "- Languages by file count: %s\n", topCounts(langs, 8))
	}
	if head, err := ws.ReadFile(".git/HEAD", 0, 0); err == nil {
		if ref, ok := strings.CutPrefix(strings.TrimSpace(head), "ref: refs/heads/"); ok {
			fmt.Fprintf(&b, "- Git branch: %s\n", ref)
		}
	}
	if len(ignore) > 0 {
		b.WriteString("- Paths matching the root .gitignore are left out below.\n")
	}

	budget := func() int { return maxBytes - b.Len() }
	section := func(title, body string, limit int) {
		limit = min(limit, budget()-len(title)-16)
		if limit < 200 || strings.TrimSpace(body) == "" {
			return
		}
		fmt.Fprintf(&b, "\n## %s\n\n%s\n", title, clip(strings.TrimSpace(body), limit))
	}

	section("Layout", layout(files, dirs, 3, 160), 12<<10)

	// Files are quoted inside fences so their own headings and code blocks
	// stay distinct from the brief's. Case-insensitive filesystems answer
	// to both justfile and Justfile, so each name is read once.
	seen := map[string]bool{}
	quote := func(title, name string, limit int) bool {
		if seen[strings.ToLower(name)] {
			return false
		}
		text, err := ws.ReadFile(name, 0, 0)
		if err != nil {
			return false
		}
		seen[strings.ToLower(name)] = true
		section(title, "~~~~\n"+clip(strings.TrimSpace(text), limit)+"\n~~~~", limit+128)
		return true
	}
	for _, name := range guidanceFiles {
		quote(name+" (project guidance: follow it)", name, 10<<10)
	}
	for _, name := range readmeFiles {
		if quote(name, name, 8<<10) {
			break
		}
	}
	for _, name := range manifests {
		quote(name, name, 3<<10)
	}
	var ci []string
	for _, f := range files {
		if strings.HasPrefix(f.Path, ".github/workflows/") || f.Path == ".gitlab-ci.yml" || strings.HasPrefix(f.Path, ".circleci/") {
			ci = append(ci, "- "+f.Path)
		}
	}
	section("CI", strings.Join(ci, "\n"), 2<<10)
	return b.String()
}

// layout renders the tree to depth levels; deeper directories are
// summarized with their file count.
func layout(files, dirs []workspace.Entry, depth, maxLines int) string {
	under := map[string]int{}
	for _, f := range files {
		for d := path.Dir(f.Path); d != "."; d = path.Dir(d) {
			under[d]++
		}
	}
	type row struct {
		p     string
		isDir bool
	}
	var rows []row
	for _, d := range dirs {
		rows = append(rows, row{d.Path, true})
	}
	for _, f := range files {
		rows = append(rows, row{f.Path, false})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].p < rows[j].p })
	var b strings.Builder
	lines, hidden := 0, 0
	for _, r := range rows {
		level := strings.Count(r.p, "/") + 1
		if level > depth {
			continue
		}
		if lines >= maxLines {
			hidden++
			continue
		}
		indent := strings.Repeat("  ", level-1)
		name := path.Base(r.p)
		switch {
		case r.isDir && level == depth:
			fmt.Fprintf(&b, "%s%s/  (%d files)\n", indent, name, under[r.p])
		case r.isDir:
			fmt.Fprintf(&b, "%s%s/\n", indent, name)
		default:
			fmt.Fprintf(&b, "%s%s\n", indent, name)
		}
		lines++
	}
	if hidden > 0 {
		fmt.Fprintf(&b, "… %d more entries (use list_dir)\n", hidden)
	}
	return b.String()
}

func topCounts(m map[string]int, n int) string {
	type kv struct {
		k string
		v int
	}
	var all []kv
	for k, v := range m {
		all = append(all, kv{k, v})
	}
	sort.Slice(all, func(i, j int) bool {
		if all[i].v != all[j].v {
			return all[i].v > all[j].v
		}
		return all[i].k < all[j].k
	})
	var parts []string
	for i, e := range all {
		if i == n {
			break
		}
		parts = append(parts, fmt.Sprintf("%s %d", e.k, e.v))
	}
	return strings.Join(parts, ", ")
}

// clip shortens text to at most n bytes at a line boundary.
func clip(text string, n int) string {
	if len(text) <= n {
		return text
	}
	cut := strings.LastIndexByte(text[:n], '\n')
	if cut < n/2 {
		cut = n
	}
	return strings.ToValidUTF8(text[:cut], "") + "\n… (truncated: read the file for the rest)"
}
