// Package onboard gets agents up to speed on a project quickly and
// cheaply, without spending model calls on it:
//
//   - Brief maps the workspace (layout, languages, agent guidance files,
//     README, build manifests, CI) for an agent's first turn, so it does
//     not have to discover the project one tool call at a time;
//   - Snapshot, Diff and Digest tell an agent exactly what changed in the
//     workspace since its last turn, and who changed it, as diffs it can
//     read instead of re-reading whole files.
package onboard

